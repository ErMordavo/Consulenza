let phraseIndex = 0;

if (indicatorText) {
    setInterval(() => {
        gsap.to(indicatorText, {
            opacity: 0,
            duration: 0.5,
            onComplete: () => {
                phraseIndex = (phraseIndex + 1) % phrases.length;
                indicatorText.innerText = currentLang === 'it' ? phrases[phraseIndex] : phrasesEn[phraseIndex];
                gsap.to(indicatorText, { opacity: 1, duration: 0.5 });
            }
        });
    }, 5000);
}

// --- BADGES CAROUSEL AUTO-SCROLL ---
const carousel = document.getElementById('badges-carousel');
if (carousel) {
    let scrollPos = 0;
    const scrollSpeed = 0.5;
    let isPaused = false;

    carousel.addEventListener('mouseenter', () => isPaused = true);
    carousel.addEventListener('mouseleave', () => isPaused = false);

    function animateCarousel() {
        if (!isPaused) {
            scrollPos += scrollSpeed;
            if (scrollPos >= carousel.scrollWidth / 2) {
                scrollPos = 0;
            }
            carousel.style.transform = `translateX(-${scrollPos}px)`;
        }
        requestAnimationFrame(animateCarousel);
    }
    
    // Clone badges for infinite loop
    const badges = carousel.innerHTML;
    carousel.innerHTML += badges;
    
    animateCarousel();
}

